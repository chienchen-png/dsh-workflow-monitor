/**
 * Assemble the single browser artifact `client.js`.
 *
 * The Web module loader takes exactly one file per package, so the fragments
 * are concatenated in dependency order inside the loader factory. Every
 * fragment is a plain script declaring exactly one top-level symbol; the
 * shared factory scope gives them `React`, `SCENE_HTML` and each other.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const order = ['bridge.js', 'mount.js'];

const sceneHtml = fs.readFileSync(path.join(root, 'src', 'scene.html'), 'utf8');
// `</script>` inside a string literal would close the host's script tag.
const sceneLiteral = JSON.stringify(sceneHtml).replace(/<\//g, '<\\/');

const fragments = order.map((file) => {
  const abs = path.join(root, 'src', file);
  if (!fs.existsSync(abs)) throw new Error(`missing fragment: src/${file}`);
  const code = fs.readFileSync(abs, 'utf8').trimEnd();
  return `    /* ================= src/${file} ================= */\n${code
    .split('\n')
    .map((line) => (line.length > 0 ? '    ' + line : line))
    .join('\n')}\n`;
});

const out = `// GENERATED by build.mjs - do not edit. dsh-workflow-monitor.
window.__ModuleLoader__.load({
  id: 'dsh-workflow-monitor',
  factory(require) {
    const React = require('react');
    const SCENE_HTML = ${sceneLiteral};
${fragments.join('\n')}
    return HalofluxMonitor;
  },
});
`;

const dest = path.join(root, 'client.js');
fs.writeFileSync(dest, out);
console.log(`client.js written: ${(out.length / 1024).toFixed(1)} KB (scene ${(sceneHtml.length / 1024).toFixed(1)} KB)`);
